SELECT
    NAME,
    SCHEDULED_TIME,
    STATE,
    QUERY_ID,
    COMPLETED_TIME,
    ERROR_MESSAGE
FROM TABLE(
    SKYPOINTS_INCU.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START => DATEADD('HOUR', -2, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 50
    )
)
WHERE NAME IN (
    'TASK_00_PREFLIGHT',
    'TASK_01_MEMBER_INGESTION',
    'TASK_02_REDEMPTION_INGESTION',
    'TASK_03_MEMBER_PROCESSING',
    'TASK_04_REDEMPTION_PROCESSING',
    'TASK_05_DATA_QUALITY'
)
